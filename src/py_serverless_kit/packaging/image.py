"""Container-image build context for ``package.type: image`` deploys.

The image is built from the same bundle as the zip (``.pskit/<provider>-<stage>/build``): pskit writes the
provider's ``Dockerfile.pskit`` and a ``.dockerignore`` next to it after the zip is made, so the zip and its hash
do not change. Terraform then builds and pushes the image (see ``providers/container.py::push_image``).
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, List

from ..providers.container import DOCKERFILE, DOCKERIGNORE, ImageBuild, image_tag, platform_for

if TYPE_CHECKING:  # pragma: no cover
    from ..config.schema import ServiceConfig
    from ..providers.base import Artifact, Provider


def dockerfile(base: str, extra: List[str], body: List[str]) -> str:
    """``FROM base`` + the user's ``package.image.dockerfile_lines`` + the provider's instructions."""
    lines = ["# Generated by py-serverless-kit (package.type: image). Do not edit: rewritten on every package.",
             f"FROM {base}"]
    lines += [line.rstrip() for line in extra if line.strip()]
    lines += body
    return "\n".join(lines) + "\n"


def prepare_image(provider: Provider, config: ServiceConfig, artifact: Artifact) -> ImageBuild:
    """Write ``Dockerfile.pskit`` and ``.dockerignore`` into the build directory and describe the image."""
    build_dir = artifact.build_dir
    if build_dir is None:  # pragma: no cover - build_artifact always sets it
        raise ValueError("the artifact has no build directory")
    text = provider.image_dockerfile(config, build_dir)
    (build_dir / DOCKERFILE).write_bytes(text.encode("utf-8"))  # LF on every OS
    (build_dir / DOCKERIGNORE).write_bytes(f"{DOCKERFILE}\n{DOCKERIGNORE}\n**/__pycache__\n**/*.pyc\n".encode())
    return ImageBuild(
        tag=image_tag(artifact, text),
        platform=platform_for(config.provider.architecture),
        dockerfile=DOCKERFILE,
        context=Path(build_dir).name,
        base_image=provider.image_base(config),
    )
